use unfog_core::NodeMetadata;

use crate::models::ExportResult;

/// Generate comprehensive ARCHITECTURE.md from repository nodes and verified understanding
pub fn generate_architecture_md(nodes: &[NodeMetadata], understood_ids: &[String]) -> String {
    let mut out = String::new();
    out.push_str("# System Architecture & Mental Models\n\n");
    out.push_str("> Generated by Unfog — The Developer Comprehension Engine\n\n");

    let total = nodes.len();
    let understood_count = understood_ids.len();
    let pct = if total > 0 {
        (understood_count * 100) / total
    } else {
        0
    };

    out.push_str("## Comprehension Overview\n");
    out.push_str(&format!(
        "- **Total Symbols Indexed**: {}\n- **Verified Understood**: {} ({}%)\n\n",
        total, understood_count, pct
    ));

    out.push_str("## Core Application Components\n\n");
    for node in nodes {
        let is_understood = understood_ids.contains(&node.id);
        let badge = if is_understood {
            "✅ [Clear / Understood]"
        } else {
            "🌫️ [Foggy]"
        };

        out.push_str(&format!("### {} `{}`\n", badge, node.label));
        out.push_str(&format!("- **File**: `{}`\n", node.file_path));
        out.push_str(&format!("- **Kind**: `{:?}`\n", node.kind));

        if let Some(route) = &node.route_path {
            out.push_str(&format!("- **Route**: `{}`\n", route));
        }

        if let Some(trigger) = &node.trigger {
            out.push_str(&format!("- **Trigger**: {}\n", trigger));
        }
        if let Some(mutation) = &node.mutation {
            out.push_str(&format!("- **Mutation**: {}\n", mutation));
        }
        if let Some(side_effects) = &node.side_effects {
            out.push_str(&format!("- **Side Effects**: {}\n", side_effects));
        }
        out.push('\n');
    }

    out.push_str("## Execution Flow Guidelines\n\n");
    out.push_str("1. **UI Layer**: User interactions fire event handlers in client components.\n");
    out.push_str("2. **State & Hooks**: Hooks coordinate state updates in local React state or global store.\n");
    out.push_str("3. **API & Services**: Network requests are dispatched to Next.js route handlers, interfacing with S3 and database services.\n\n");

    out
}

/// Generate project-specific .cursorrules from codebase mental models
pub fn generate_cursorrules(nodes: &[NodeMetadata], understood_ids: &[String]) -> String {
    let mut out = String::new();
    out.push_str("# Project Cursor Rules\n");
    out.push_str("# Invariants and Architectural Conventions extracted by Unfog\n\n");

    out.push_str("## Architecture Invariants\n");
    out.push_str("- Keep client-side state synchronized using reactive store conventions.\n");
    out.push_str("- Always validate file size and content type before dispatching uploads.\n");
    out.push_str("- Asynchronous operations must be guarded with proper try/catch and loading state cleanup in `finally` blocks.\n");
    out.push_str("- Never mutate database or cloud storage directly from UI components; always dispatch through dedicated API route handlers.\n\n");

    out.push_str("## Understood System Modules\n");
    for node in nodes {
        if understood_ids.contains(&node.id) {
            out.push_str(&format!(
                "- `{}` ({:?} in `{}`): Trigger: {}, Mutation: {}\n",
                node.label,
                node.kind,
                node.file_path,
                node.trigger.as_deref().unwrap_or("Invoked"),
                node.mutation.as_deref().unwrap_or("Processes state")
            ));
        }
    }

    out
}

/// Generate full export bundle
pub fn generate_export(nodes: &[NodeMetadata], understood_ids: &[String]) -> ExportResult {
    ExportResult {
        architecture_md: generate_architecture_md(nodes, understood_ids),
        cursorrules: generate_cursorrules(nodes, understood_ids),
    }
}
