use std::collections::HashMap;
use unfog_core::NodeMetadata;

pub struct Exporter;

impl Exporter {
    pub fn generate_architecture_md(
        nodes: &[&NodeMetadata],
        understood: &HashMap<String, String>,
    ) -> String {
        let mut md = String::new();
        md.push_str("# System Architecture & Mental Models\n\n");
        md.push_str("> Auto-generated by Unfog based on verified comprehension milestones.\n\n");

        md.push_str("## Core Execution Pipeline\n\n");
        md.push_str("```mermaid\ngraph LR\n");
        for (i, node) in nodes.iter().enumerate() {
            let label = node.label.replace('"', "");
            md.push_str(&format!("  n{}[\"{}\"]\n", i, label));
            if i > 0 {
                md.push_str(&format!("  n{} --> n{}\n", i - 1, i));
            }
        }
        md.push_str("```\n\n");

        md.push_str("## Verified Modules & Components\n\n");
        for node in nodes {
            let status = understood.get(&node.id).map(|s| s.as_str()).unwrap_or("Unverified");
            md.push_str(&format!("### `{}` ({:?})\n", node.label, node.kind));
            md.push_str(&format!("- **File:** `{}`\n", node.file_path));
            md.push_str(&format!("- **Status:** {}\n", status));
            if let Some(t) = &node.trigger {
                md.push_str(&format!("- **Trigger:** {}\n", t));
            }
            if let Some(m) = &node.mutation {
                md.push_str(&format!("- **Mutation:** {}\n", m));
            }
            if let Some(s) = &node.side_effects {
                md.push_str(&format!("- **Side Effects:** {}\n", s));
            }
            md.push('\n');
        }

        md
    }

    pub fn generate_cursorrules(
        nodes: &[&NodeMetadata],
        _understood: &HashMap<String, String>,
    ) -> String {
        let mut rules = String::new();
        rules.push_str("# Unfog AI Rules for Cursor & Assistant Prompting\n\n");
        rules.push_str("# Architecture Constraints\n");
        rules.push_str("- Preserve established execution flows without introducing duplicate abstractions.\n");
        rules.push_str("- When modifying backend services or S3 uploads, ensure route handlers in `/api/upload` remain backward compatible.\n\n");

        rules.push_str("# Key Components & Dependencies\n");
        for node in nodes {
            rules.push_str(&format!("- `{}` (`{}`): {}\n", node.label, node.file_path, node.trigger.as_deref().unwrap_or("core module")));
        }
        rules.push_str("\n# Testing & Verification Rules\n");
        rules.push_str("- Run tests before and after modifying shared state hooks.\n");
        rules.push_str("- Do not hardcode secret keys or tokens in code; use environment variables.\n");

        rules
    }
}
